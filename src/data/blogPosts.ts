export function getRelatedContent(currentHref: string, limit = 2): ContentItem[] {
  const all = getAllContent()
  const currentIndex = all.findIndex((item) => item.href === currentHref)

  return all
    .map((item, index) => ({ item, distance: Math.abs(index - currentIndex) }))
    .filter(({ item }) => item.href !== currentHref)
    .sort((a, b) => a.distance - b.distance)
    .slice(0, limit)
    .map(({ item }) => item)
}
